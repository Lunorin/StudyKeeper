PERSONAS = {
    "default": PERSONA_DEFAULT,
    "zeng_guofan": PERSONA_ZENG_GUOFAN,
    "truth_doctor": PERSONA_TRUTH_DOCTOR,
}


def get_persona_prompt(persona_id: str) -> str:
    """返回 persona_id 对应的人格设定段；未知 / None / 空串一律回退 PERSONA_DEFAULT。

    只做「查表」，不做合法性校验（合法性由 Java 侧把关），且永远不返回空串。
    """
    if not isinstance(persona_id, str):
        return PERSONA_DEFAULT
    return PERSONAS.get(persona_id, PERSONA_DEFAULT)
